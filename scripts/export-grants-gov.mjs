#!/usr/bin/env node
// Proposal Studio v2 — Phase 3 Grants.gov XML form-mapping export (added 2026-05-27)
//
// Reads a proposal markdown file + an org-profile JSON and emits a
// Grants.gov-shaped XML envelope for the SF-424 Application for Federal
// Assistance (R&R variant) — the universal federal cover form.
//
// This is NOT a full Grants.gov S2S submission — it's a structured XML the
// user can review, hand-edit, and submit through Workspace. Federal S2S
// requires Adobe XFA fillable PDFs + Workspace API credentials; out of scope
// for the fork MVP.
//
// Usage:
//   node scripts/export-grants-gov.mjs <proposal.md> <org-profile.json> [output.xml]
//
// org-profile.json shape:
//   {
//     "legalName": "The Collaborative Advocate Foundation",
//     "ein": "41-3618003",
//     "uei": "KDDVD1FGLW35",
//     "cage": "209N1",
//     "address": { "line1": "...", "city": "...", "state": "TX", "zip": "..." },
//     "authorizedRep": { "name": "...", "title": "...", "email": "...", "phone": "..." },
//     "opportunityNumber": "...",
//     "projectTitle": "...",
//     "startDate": "YYYY-MM-DD",
//     "endDate": "YYYY-MM-DD",
//     "requestedAmount": 1000000
//   }
//
// Fork-ready: zero deps.

import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

function xmlEscape(s) {
  if (s === null || s === undefined) return "";
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function extractAbstract(md, maxChars = 4000) {
  // Pull first non-heading paragraph after "## The intervention" or "## Working title"
  const after = md.split(/^##\s+(?:the intervention|working title)/im)[1];
  if (!after) return md.slice(0, maxChars);
  const paragraphs = after.split(/\n\n+/).filter((p) => !p.trim().startsWith("#") && p.trim().length > 0);
  return paragraphs.slice(0, 4).join("\n\n").slice(0, maxChars);
}

function main() {
  const mdPath = process.argv[2];
  const profilePath = process.argv[3];
  if (!mdPath || !profilePath) {
    console.error("Usage: node scripts/export-grants-gov.mjs <proposal.md> <org-profile.json> [output.xml]");
    process.exit(2);
  }
  const outPath = process.argv[4] ?? mdPath.replace(/\.md$/i, "") + ".grants-gov.xml";

  const md = readFileSync(resolve(mdPath), "utf8");
  const profile = JSON.parse(readFileSync(resolve(profilePath), "utf8"));
  const abstract = extractAbstract(md);

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<GrantApplicationPackage xmlns="http://apply.grants.gov/system/Header-V1.0"
                         exportedAt="${new Date().toISOString()}"
                         note="Generated by ThriveUp/RPLICE Proposal Studio v2. Hand-review before Grants.gov Workspace submission.">
  <SF424_2_1>
    <SubmissionType>Application</SubmissionType>
    <ApplicationType>New</ApplicationType>
    <ApplicantInfo>
      <OrganizationName>${xmlEscape(profile.legalName)}</OrganizationName>
      <EmployerTaxpayerIdentificationNumber>${xmlEscape(profile.ein)}</EmployerTaxpayerIdentificationNumber>
      <UEI>${xmlEscape(profile.uei)}</UEI>
      <CAGECode>${xmlEscape(profile.cage)}</CAGECode>
      <Address>
        <Street1>${xmlEscape(profile.address?.line1)}</Street1>
        <City>${xmlEscape(profile.address?.city)}</City>
        <State>${xmlEscape(profile.address?.state)}</State>
        <ZipPostalCode>${xmlEscape(profile.address?.zip)}</ZipPostalCode>
        <Country>USA</Country>
      </Address>
      <AuthorizedRepresentative>
        <Name>${xmlEscape(profile.authorizedRep?.name)}</Name>
        <Title>${xmlEscape(profile.authorizedRep?.title)}</Title>
        <Email>${xmlEscape(profile.authorizedRep?.email)}</Email>
        <Phone>${xmlEscape(profile.authorizedRep?.phone)}</Phone>
      </AuthorizedRepresentative>
    </ApplicantInfo>
    <FederalOpportunity>
      <OpportunityNumber>${xmlEscape(profile.opportunityNumber)}</OpportunityNumber>
    </FederalOpportunity>
    <Project>
      <ProjectTitle>${xmlEscape(profile.projectTitle)}</ProjectTitle>
      <StartDate>${xmlEscape(profile.startDate)}</StartDate>
      <EndDate>${xmlEscape(profile.endDate)}</EndDate>
      <RequestedAmount>${xmlEscape(profile.requestedAmount)}</RequestedAmount>
      <ProjectAbstract><![CDATA[${abstract}]]></ProjectAbstract>
    </Project>
  </SF424_2_1>
</GrantApplicationPackage>
`;

  writeFileSync(resolve(outPath), xml, "utf8");
  console.log(`Wrote SF-424 XML envelope → ${outPath}`);
  console.log("NOTE: Hand-review before Workspace submission. S2S submission requires Adobe XFA + Workspace API credentials (out of scope for fork MVP).");
}

main();
