/**
 * Returns true when `pathname` matches a known public route.
 * Strips trailing slashes before comparison (except for root "/").
 */
export function isKnownPublicPath(pathname: string): boolean {
  const clean = pathname === "/" ? "/" : pathname.replace(/\/+$/, "");

  if (STATIC_PATHS.has(clean)) return true;

  for (const pattern of DYNAMIC_PATTERNS) {
    if (pattern.test(clean)) return true;
  }

  return false;
}
